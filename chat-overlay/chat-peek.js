(function () {
  if (window.MedsiChatPeek) return;
  const HOLD_MS = 450;
  let press = null;
  let modal = null;
  let sourceCard = null;
  let ignoreReleaseClick = false;

  function cancelPress() {
    if (press) clearTimeout(press.timer);
    press = null;
  }

  function cardFor(event) {
    if (document.body.dataset.screen !== 'screenChats') return null;
    const target = event.target;
    if (!target || !target.closest || target.closest('.chat-controls')) return null;
    const card = target.closest('#chatList > .chat-card');
    return card && card.closest('.educator-exact-clone') ? card : null;
  }

  function close() {
    cancelPress();
    if (!modal) return;
    modal.remove();
    modal = null;
    document.body.classList.remove('medsi-chat-peek-open');
    if (sourceCard && sourceCard.isConnected) sourceCard.focus({ preventScroll: true });
    sourceCard = null;
  }

  // The list already contains the full latest message. Reading this DOM copy
  // never opens a thread, requests messages, or sends a read receipt.
  function open(card) {
    cancelPress();
    if (!card.isConnected || document.body.dataset.screen !== 'screenChats') return;
    close();
    sourceCard = card;
    const last = card.querySelector('.chat-card-last');
    const educator = !!(last && last.classList.contains('educator'));
    modal = document.createElement('div');
    modal.className = 'medsi-chat-peek-backdrop';
    modal.innerHTML = '<section class="medsi-chat-peek" role="dialog" aria-modal="true" aria-labelledby="medsiChatPeekTitle"><header><h2 id="medsiChatPeekTitle"></h2><button type="button" class="medsi-chat-peek-close" aria-label="Закрыть превью">×</button></header><div class="medsi-chat-peek-message" tabindex="0"></div></section>';
    modal.querySelector('h2').textContent = educator ? 'Вы' : (card.querySelector('.chat-card-meta')?.textContent.split('\n')[0] || 'Родитель').replace(/:\s*/, ' ');
    modal.querySelector('.medsi-chat-peek').classList.toggle('from-educator', educator);
    const message = modal.querySelector('.medsi-chat-peek-message');
    message.textContent = last?.textContent || 'Нет сообщений';
    modal.querySelector('.medsi-chat-peek-close').onclick = close;
    modal.addEventListener('click', event => { if (event.target === modal) close(); });
    document.body.appendChild(modal);
    document.body.classList.add('medsi-chat-peek-open');
    modal.querySelector('button').focus({ preventScroll: true });
  }

  document.addEventListener('pointerdown', event => {
    ignoreReleaseClick = false;
    cancelPress();
    if (event.button !== 0 || event.isPrimary === false || modal) return;
    const card = cardFor(event);
    if (!card) return;
    press = { x: event.clientX, y: event.clientY, id: event.pointerId, timer: setTimeout(() => {
      open(card);
      ignoreReleaseClick = true;
    }, HOLD_MS) };
  }, { capture: true, passive: true });

  document.addEventListener('pointermove', event => {
    if (press && (event.pointerId !== press.id || Math.hypot(event.clientX - press.x, event.clientY - press.y) > 12)) cancelPress();
  }, { capture: true, passive: true });
  ['pointerup', 'pointercancel', 'scroll'].forEach(type => document.addEventListener(type, cancelPress, { capture: true, passive: true }));

  // Swallow the click generated by releasing a long press, before the card's
  // normal click handler can open the thread and mark it read.
  document.addEventListener('click', event => {
    if (!ignoreReleaseClick) return;
    ignoreReleaseClick = false;
    event.preventDefault();
    event.stopImmediatePropagation();
  }, true);

  document.addEventListener('contextmenu', event => {
    const card = cardFor(event);
    if (!card) return;
    event.preventDefault();
    event.stopImmediatePropagation();
    if (!modal) open(card);
    ignoreReleaseClick = true;
  }, true);

  document.addEventListener('keydown', event => {
    if (!modal) {
      if (event.key === 'ContextMenu' || (event.shiftKey && event.key === 'F10')) {
        const card = cardFor(event);
        if (card) { event.preventDefault(); open(card); }
      }
      return;
    }
    if (event.key === 'Escape') { event.preventDefault(); event.stopImmediatePropagation(); close(); }
    if (event.key === 'Tab') {
      const first = modal.querySelector('button');
      const last = modal.querySelector('.medsi-chat-peek-message');
      if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
      else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
    }
  }, true);

  new MutationObserver(() => {
    if (document.body.dataset.screen !== 'screenChats') close();
  }).observe(document.body, { attributes: true, attributeFilter: ['data-screen'] });
  window.addEventListener('blur', () => { cancelPress(); close(); });
  window.MedsiChatPeek = { close };
})();
