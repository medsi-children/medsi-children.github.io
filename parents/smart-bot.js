/*
 * Правила распознавания для Медси Бота.
 * Файл не подключён к основной панели: его можно использовать в лаборатории и
 * позднее подключить к ней отдельно, передав безопасные действия интерфейса.
 */
(() => {
  'use strict';

  function normalize(text) {
    return ` ${String(text || '').toLocaleLowerCase('ru')
      .replace(/ё/g, 'е')
      .replace(/[^а-яa-z0-9]+/g, ' ')
      .trim()} `;
  }

  function classify(text) {
    const query = normalize(text);
    const has = pattern => pattern.test(query);

    // Более конкретные темы идут первыми, чтобы общие слова «врач», «отчёт»
    // и «занятия» не перехватывали разговор о встречах и психотерапии.
    if (has(/ (?:спасибо|благодар|супер|отлично|здорово)/) && !has(/ (?:как|когда|где|почему|можно|нужно|сколько|какой|какая)/)) return 'thanks';
    if (has(/ (?:оплат|стоимост|цен[аеу]|платеж|заплат|квитанц)/)) return 'payment';
    if (has(/ (?:телефон|номер|контакт|связат|позвон)/) && has(/ (?:врач|лечащ|анастас|антон геннад)/)) return 'doctors';

    const groupTherapy = has(/ (?:групп|общ[а-я]* (?:занят|психотерап))/) && has(/ (?:психотерап|терапи|психолог|занят|отчет)/);
    if (groupTherapy) return has(/ (?:когда|во сколько|время|расписан|начина|проходят)/) ? 'groupTherapyTime' : 'groupTherapy';
    const individualTherapy = has(/ (?:индивидуал|личн)/) && has(/ (?:психотерап|терапи|психолог|занят)/)
      || has(/ (?:занят[а-я]* (?:с )?психолог|психолог[а-я]* занят|мо[йи] психолог|сво[йи] психолог|психологом|психологу|связат[а-я]* с психолог)/);
    if (individualTherapy) return 'individualTherapy';
    if (has(/ (?:психотерап|психолог|терапи)/)) return 'therapy';

    if (has(/ (?:срочн|экстренн|неотложн)/)) return 'urgent';
    if (has(/ (?:войти|вход|авторизац|код подтвержден|подтвержден.*код|смс код|не пуска|не могу зайти|не получается зайти)/)) return 'signIn';

    const childVisit = has(/ (?:встреч|встрет|увид|видет|повида|навещ|проведа|приеха|приед|приезд|прийт|прийти|приход|посет|посещ|свидан|навест)/)
      && (!has(/ (?:врач|доктор|лечащ)/) || has(/ (?:ребен|дочк|сын|дет[ьи])/));
    if (childVisit) {
      if (has(/ (?:когда|во сколько|время|час|расписан|до скольк|со скольк|в какие дни|в какой день|можно встрет|могу встрет|можно увид|могу увид|можно приех|могу приех)/)) return 'meetTime';
      return 'meetings';
    }
    if (has(/ (?:звон|созвон|позвон|поговор|связат)/) && has(/ (?:ребен|дочк|сын|дет[ьи]|звонк)/)) return 'calls';

    const report = has(/ (?:отчет|сводк|наблюден)/)
      || has(/ (?:утренн|вечерн)/) && has(/ (?:покаж|отправ|скин|присл|пришл|посмотр|откры|когда|будет|готов|нов[а-я]*|почему|нет|задерж)/);
    if (report) {
      const kind = has(/ утренн/) && !has(/ вечерн/) ? 'morning' : has(/ вечерн/) && !has(/ утренн/) ? 'evening' : '';
      const delayed = has(/ (?:до сих пор|почему|нет|не приш|не появ|не виж|где|опозд|задерж|жду|стар[а-я]* отчет|не готов|не получил|не появил)/);
      const requested = has(/ (?:покаж|отправ|скин|присл|пришл|посмотр|откры|дай|дайте|получ|хочу|последн|актуальн)/);
      if (delayed) return { key: 'reportDelay', kind };
      if (has(/ (?:когда|во сколько|время|расписан|ждать|будет)/) && !requested) return 'reports';
      if (kind || requested) return { key: 'reportRequest', kind };
      return 'reports';
    }

    if (has(/ (?:режим дня|распоряд|расписан|подъем|завтрак|обед|полдник|ужин|сон час|отбой|прогулк|зарядк|йог|киносеанс)/)) return 'routine';

    if (has(/ (?:лекарств|таблет|медикамент|препарат)/)) return 'medical';

    const deliveryVerb = has(/ (?:достав|переда|передат|привез|принес|заказ|отправ|полож|куп|курьер|гринвуд)/);
    const deliveryThing = has(/ (?:ед[ауы]|вкусн|сладост|фрукт|пицц|суши|напит|одежд|вещ|посыл|передач|игрушк|книг|продукт|посылк|творческ[а-я]* набор)/);
    if (deliveryVerb || deliveryThing) return 'delivery';

    if (has(/ (?:врач|лечащ|лечение|лечить|препарат|таблет|лекарств|анализ|процедур|диагноз)/)) return 'medical';
    if (has(/ (?:не отвеч|нет ответ|долго молч|почему молч|когда ответ)/) && has(/ (?:воспитател| чат |сообщен)/)) return 'educators';
    if (has(/ (?:напис|связат|чат|сообщен|вопрос)/) && has(/ воспитател/)) return 'writeEducators';
    if (has(/ (?:воспитател|написат.*вопрос| чат )/)) return 'educators';
    if (has(/ (?:экран домой| домой |приложен|установ|ярлык)/)) return 'home';
    return null;
  }

  window.MedsiSmartBot = Object.freeze({ normalize, classify });
})();
